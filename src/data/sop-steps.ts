export function getStepsByStage(stageIndex: number): SopStep[] {
  return sopSteps.filter((step) => step.stageIndex === stageIndex);
}

export function getCurrentStepIndex(currentStepId: number): number {
  return sopSteps.findIndex((step) => step.id === currentStepId);
}

export function getStepStatus(stepId: number, currentStepId: number): 'completed' | 'current' | 'locked' {
  if (stepId < currentStepId) return 'completed';
  if (stepId === currentStepId) return 'current';
  return 'locked';
}
